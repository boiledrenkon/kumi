-- What Kumi deleted and put back is the same object to its earlier changes (M4, n-instruments): an instrument, a sample, a phrase,
-- a modulation set or a sample FX chain, a device. Kumi's undo of a change made before the delete finds it where it came back
-- (and what is in it), also after the producer moved things since; Renoise's own undo of the delete isn't Kumi's put-back.
local T = ...
local mock = T.mock
local json = T.load_payload_module("json")
local test, eq, ok = T.test, T.eq, T.ok
local I, F = T.instruments, T.modfx
local setup, place, change, restore, failure, instrument, iref, sref = I.setup, I.place, I.change, I.restore, I.failure, I.instrument, I.iref, I.sref

local function pref(E, i, p) return E .. ":phrase:" .. i .. "." .. p end
local function undone(peer, kind, record, what)
  local answer = restore(peer, kind, record)
  ok(answer.result, (what or kind) .. ": " .. json.encode(answer.error or {}))
  return answer
end

test("continuity: an instrument Kumi deleted and put back keeps its earlier changes' places: its name, a sample's, a phrase's, a set's", function()
  local env, peer = setup()
  local E = place(peer)
  local renamed = change(peer, "instrument-rename", { ref = iref(E, 2), name = "Acid" })
  local volume = change(peer, "sample-set", { ref = sref(place(peer), 2, 1), volumeDb = -6 })
  local lpb = change(peer, "phrase-set", { ref = pref(place(peer), 2, 1), lpb = 8 })
  local pitch = change(peer, "modset-set", { ref = place(peer) .. ":modset:2.1", pitchRange = 24 })
  local deleted = change(peer, "instrument-delete", { ref = iref(place(peer), 2) })
  eq(#mock.data.instruments, 2)
  undone(peer, "instrument-delete", deleted)
  eq(instrument(2).name, "Acid")
  -- (and the producer made an instrument before it since)
  mock.ops.insert_instrument_at(1, { name = "New" })
  undone(peer, "modset-set", pitch)
  eq(instrument(3).sets[1].pitch_range, 12)
  undone(peer, "phrase-set", lpb)
  eq(instrument(3).phrases[1].lpb, 4)
  undone(peer, "sample-set", volume)
  eq(instrument(3).samples[1].volume, 1)
  undone(peer, "instrument-rename", renamed)
  eq(instrument(3).name, "Bass synth")
end)

test("continuity: a sample and a phrase Kumi deleted and put back keep their earlier changes' places, and the phrase its lines' count", function()
  local env, peer = setup()
  local volume = change(peer, "sample-set", { ref = sref(place(peer), 1, 2), volumeDb = -12 })
  local deleted = change(peer, "sample-delete", { ref = sref(place(peer), 1, 2) })
  undone(peer, "sample-delete", deleted)
  mock.ops.insert_sample(1)
  undone(peer, "sample-set", volume)
  eq(instrument(1).samples[2].volume, 1)
  local lines = change(peer, "phrase-write", { ref = pref(place(peer), 2, 1), lines = { { line = 1, notes = { { col = 1, note = "C-4" } } } } })
  local lpb = change(peer, "phrase-set", { ref = pref(place(peer), 2, 1), lpb = 8 })
  local gone = change(peer, "phrase-delete", { ref = pref(place(peer), 2, 1) })
  undone(peer, "phrase-delete", gone)
  undone(peer, "phrase-set", lpb)
  undone(peer, "phrase-write", lines, "the plain rule follows the phrase put back")
  eq(mock.song:instrument(2):phrase(1):line(2):note_column(1).note_string, "---")
end)

test("continuity: a set, a chain and their devices Kumi deleted and put back keep the places of what was changed in them before", function()
  local env, peer, E = F.setup()
  local attack = change(peer, "moddevice-param", { ref = E .. ":moddevice:1.1.1", param = "Attack", value = 0.3 })
  local range = change(peer, "modset-set", { ref = place(peer) .. ":modset:1.1", pitchRange = 24 })
  local set_gone = change(peer, "modset-delete", { ref = place(peer) .. ":modset:1.1" })
  undone(peer, "modset-delete", set_gone)
  undone(peer, "modset-set", range)
  eq(instrument(1).sets[1].pitch_range, 12)
  undone(peer, "moddevice-param", attack, "a device in the set put back")
  eq(instrument(1).sets[1].devices[1].params[1].value, 0.1)
  -- (a device's state goes back as its preset data, which the mock doesn't read parameters from: its bypass, which it keeps)
  local bypass = change(peer, "chaindevice-bypass", { ref = place(peer) .. ":chaindevice:1.1.2", bypass = true })
  local renamed = change(peer, "chain-set", { ref = place(peer) .. ":chain:1.1", name = "Air" })
  local chain_gone = change(peer, "chain-delete", { ref = place(peer) .. ":chain:1.1" })
  undone(peer, "chain-delete", chain_gone)
  undone(peer, "chain-set", renamed)
  eq(instrument(1).chains[1].name, "Tone")
  undone(peer, "chaindevice-bypass", bypass, "a device in the chain put back")
  eq(instrument(1).chains[1].devices[2].active, true)
  local again = change(peer, "chaindevice-bypass", { ref = place(peer) .. ":chaindevice:1.1.2", bypass = true })
  local device_gone = change(peer, "chaindevice-delete", { ref = place(peer) .. ":chaindevice:1.1.2" })
  undone(peer, "chaindevice-delete", device_gone)
  undone(peer, "chaindevice-bypass", again, "the device put back")
  eq(instrument(1).chains[1].devices[2].active, true)
  local turned = change(peer, "moddevice-set", { ref = place(peer) .. ":moddevice:1.1.2", bipolar = true })
  local moddevice_gone = change(peer, "moddevice-delete", { ref = place(peer) .. ":moddevice:1.1.2" })
  undone(peer, "moddevice-delete", moddevice_gone)
  undone(peer, "moddevice-set", turned, "the modulation device put back")
  eq(instrument(1).sets[1].devices[2].bipolar, false)
end)

test("continuity: what Renoise's own undo brings back isn't Kumi's put-back: the change before it says gone, and writes nothing", function()
  local env, peer = setup()
  local volume = change(peer, "sample-set", { ref = sref(place(peer), 1, 2), volumeDb = -12 })
  change(peer, "sample-delete", { ref = sref(place(peer), 1, 2) })
  mock.song:undo()
  eq(#instrument(1).samples, 3, "Renoise's undo brought it")
  local before = I.steps()
  failure(restore(peer, "sample-set", volume), "gone")
  eq(I.steps(), before)
end)
