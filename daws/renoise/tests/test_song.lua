test("song: the undo of a precount or a record quantize puts back the bars or lines Renoise keeps while it is off", function()
  local _, peer = K.setup()
  mock.ops.transport("metronome_precount_bars", 3)
  mock.ops.transport("record_quantize_lines", 4)
  local precount = K.change(peer, "metronome-switch", { precount = 1 })
  local quantize = K.change(peer, "edit-settings", { quantize = 8 })
  eq(transport().metronome_precount_bars, 1)
  eq(transport().record_quantize_lines, 8)
  ok(K.restore(peer, precount).result)
  ok(K.restore(peer, quantize).result)
  eq(transport().metronome_precount_enabled, false)
  eq(transport().metronome_precount_bars, 3, "the bars it had, off")
  eq(transport().record_quantize_enabled, false)
  eq(transport().record_quantize_lines, 4)
  -- turning it off when it is off changes nothing
  eq(K.preview(peer, "metronome-switch", { precount = false }).display.unchanged, true)
  H.no_dialogs()
end)
