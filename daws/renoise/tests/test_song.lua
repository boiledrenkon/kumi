-- M4 (n-song): Kumi's changes to the song's settings (the groove, the metronome, the editing settings, the name, artist and
-- comments, the track headroom): preview, apply, restore, the producer's change in between, Renoise's undo told.
local T = ...
local mock = T.mock
local test, eq, ok = T.test, T.eq, T.ok
local H = T.harness
local K = assert(loadfile(T.tests_dir .. "change_kit.lua"))(T)

local function transport() return mock.data.transport_fields end
local MINUS = "\226\136\146"

test("song: the groove changes as one undo step and goes back as another", function()
  local _, peer = K.setup()
  local previewed = K.preview(peer, "song-groove", { on = true, amounts = { 0.25, 0.5, 0.75, 1 } })
  eq(previewed.display.title, "Groove on, 25% 50% 75% 100%")
  eq(previewed.prior.on, false)
  eq(K.steps(), 0, "a preview writes nothing")
  eq(mock.data.groove.enabled, false)
  local record = K.change(peer, "song-groove", { on = true, amounts = { 0.25, 0.5, 0.75, 1 } }, "Kumi: Groove on (kg01)")
  eq(record.result.undo.entry, true)
  eq(K.steps(), 1)
  eq(K.newest(), "Kumi: Groove on (kg01)")
  eq(mock.data.groove.enabled, true)
  eq(mock.data.groove.amounts[3], 0.75)
  local undone = K.restore(peer, record, "Kumi: undo Groove on (kg02)")
  ok(undone.result, "restored")
  eq(undone.result.undo.entry, true)
  eq(K.steps(), 2, "a new step, never Renoise's undo")
  eq(K.newest(), "Kumi: undo Groove on (kg02)")
  eq(mock.data.groove.enabled, false)
  eq(mock.data.groove.amounts[3], 0)
  -- back already: nothing written
  local again = K.restore(peer, record)
  ok(again.result)
  eq(again.result.display.note, "It was back already: nothing was written.")
  eq(K.steps(), 2)
  H.no_dialogs()
end)

test("song: only the settings a change gives are fenced and put back", function()
  local _, peer = K.setup()
  local record = K.change(peer, "edit-settings", { editStep = 4 })
  eq(transport().edit_step, 4)
  eq(record.prior.editStep, 1)
  eq(record.prior.octave, nil, "the octave isn't the change's")
  -- the producer changes the octave meanwhile: Kumi's undo of the edit step goes through and leaves the octave
  mock.ops.transport("octave", 5)
  local undone = K.restore(peer, record)
  ok(undone.result, "restored")
  eq(transport().edit_step, 1)
  eq(transport().octave, 5)
  H.no_dialogs()
end)

test("song: a producer change in between refuses the undo, and discard puts it back anyway", function()
  local _, peer = K.setup()
  local record = K.change(peer, "song-metronome", { beatsPerBar = 3, volumeDb = -6 })
  eq(transport().metronome_beats_per_bar, 3)
  ok(math.abs(transport().metronome_volume - 10 ^ (-6 / 20)) < 1e-6)
  mock.ops.transport("metronome_beats_per_bar", 7)
  local refused = K.restore(peer, record)
  local message = K.failure(refused, "changed")
  ok(message:find("metronome changed in Renoise since Kumi set it", 1, true), message)
  eq(transport().metronome_beats_per_bar, 7, "the producer's stays")
  local forced = K.restore(peer, record, nil, { discard = true })
  ok(forced.result, "discard puts it back")
  eq(transport().metronome_beats_per_bar, 0)
  ok(math.abs(transport().metronome_volume - 0.70794576406479) < 1e-6)
  H.no_dialogs()
end)

test("song: an apply after the producer changed the setting is refused before anything is written (the fence)", function()
  local _, peer = K.setup()
  local previewed, epoch, layout = K.preview(peer, "song-headroom", { headroomDb = -3 })
  mock.ops.transport("track_headroom", 1)
  local refused = K.apply(peer, "song-headroom", { headroomDb = -3 }, "Kumi: h (kh01)", previewed.fence, epoch, layout)
  K.failure(refused, "changed")
  eq(transport().track_headroom, 1, "left as the producer had it")
  eq(K.steps(), 0)
  H.no_dialogs()
end)

test("song: the metronome switch and the editing settings are no undo steps and say so", function()
  local _, peer = K.setup()
  local record = K.change(peer, "metronome-switch", { on = true, precount = 2 })
  eq(record.result.undo.entry, false)
  eq(record.result.display.title, "Metronome on, 2-bar precount")
  eq(record.result.display.note, "Renoise's own undo won't take this back; Kumi can.")
  eq(transport().metronome_enabled, true)
  eq(transport().metronome_precount_enabled, true)
  eq(transport().metronome_precount_bars, 2)
  eq(K.steps(), 0, "no undo step")
  local undone = K.restore(peer, record)
  ok(undone.result)
  eq(transport().metronome_enabled, false)
  eq(transport().metronome_precount_enabled, false)
  local editing = K.change(peer, "edit-settings", { followPlayer = true, quantize = 2, keyboardVelocity = 100, recordTo = "automation" })
  eq(editing.result.undo.entry, false)
  eq(editing.result.display.title, "Follow player on, record quantize 2 lines, keyboard velocity 100, parameters recorded to the automation")
  eq(transport().record_quantize_enabled, true)
  eq(transport().record_quantize_lines, 2)
  eq(transport().keyboard_velocity_enabled, true)
  eq(transport().record_parameter_mode, 2)
  K.restore(peer, editing)
  eq(transport().record_quantize_enabled, false)
  eq(transport().keyboard_velocity_enabled, false)
  eq(transport().record_parameter_mode, 1)
  eq(K.steps(), 0)
  H.no_dialogs()
end)

test("song: the name, artist and comments change and go back; comments are taken as text or lines", function()
  local _, peer = K.setup()
  local record = K.change(peer, "song-info", { name = "Night Drive", artist = "Kumi", comments = "first line\nsecond line" })
  eq(record.result.display.title, "Song named \226\128\156Night Drive\226\128\157, by \226\128\156Kumi\226\128\157, comments changed")
  eq(mock.song.name, "Night Drive")
  eq(mock.song.artist, "Kumi")
  eq(table.concat(mock.song.comments, "|"), "first line|second line")
  eq(K.steps(), 1)
  K.restore(peer, record)
  eq(mock.song.name, "Lab")
  eq(mock.song.artist, "")
  eq(#mock.song.comments, 0)
  local lines = K.change(peer, "song-info", { comments = { "a", "b" } })
  eq(table.concat(mock.song.comments, "|"), "a|b")
  eq(lines.result.display.title, "Song comments changed")
  H.no_dialogs()
end)

test("song: Renoise's undo of a song setting is told, and its redo", function()
  local _, peer = K.setup()
  K.change(peer, "song-groove", { amounts = { 0.5, 0, 0.5, 0 } }, "Kumi: groove (kg11)")
  K.change(peer, "song-info", { artist = "Someone" }, "Kumi: artist (ka11)")
  K.change(peer, "song-headroom", { headroomDb = -9 }, "Kumi: headroom (kh11)")
  K.told(peer)
  mock.song:undo()
  eq(K.told(peer), "undo:Kumi: headroom (kh11)")
  mock.song:undo()
  eq(K.told(peer), "undo:Kumi: artist (ka11)")
  mock.song:undo()
  eq(K.told(peer), "undo:Kumi: groove (kg11)")
  mock.song:redo()
  eq(K.told(peer), "redo:Kumi: groove (kg11)")
  H.no_dialogs()
end)

test("song: bad settings are bad-params and write nothing", function()
  local _, peer = K.setup()
  local function bad(kind, input)
    local response = K.ask(peer, "change_preview", kind, input)
    K.failure(response, "bad-params")
  end
  bad("song-groove", {})
  bad("song-groove", { amounts = { 0.5, 0.5, 0.5 } })
  bad("song-groove", { amounts = { 0.5, 0.5, 0.5, 2 } })
  bad("song-groove", { on = "yes" })
  bad("song-metronome", { beatsPerBar = 17 })
  bad("song-metronome", { linesPerBeat = 1.5 })
  bad("song-metronome", { volumeDb = 7 })
  bad("metronome-switch", { precount = 5 })
  bad("metronome-switch", { precount = true })
  bad("edit-settings", { editStep = 65 })
  bad("edit-settings", { octave = 9 })
  bad("edit-settings", { quantize = 33 })
  bad("edit-settings", { keyboardVelocity = 128 })
  bad("edit-settings", { recordTo = "clip" })
  bad("song-info", { name = "two\nlines" })
  bad("song-info", { comments = 3 })
  bad("song-headroom", { headroomDb = 1 })
  bad("song-headroom", { headroomDb = -13 })
  eq(K.steps(), 0)
  H.no_dialogs()
end)

test("song: a song opened since makes the record stale, and nothing is written", function()
  local _, peer = K.setup()
  local record = K.change(peer, "song-groove", { on = true })
  mock.fire(mock.tool.app_new_document_observable)
  local stale = K.restore(peer, record)
  K.failure(stale, "stale")
  eq(mock.data.groove.enabled, true)
  H.no_dialogs()
end)

test("song: the song row shows the settings the song kinds change", function()
  local _, peer = K.setup()
  mock.data.info.artist = "Somebody"
  mock.data.info.comments = { string.rep("x", 600), string.rep("\195\169", 300) }
  mock.ops.transport("edit_step", 2)
  local row = K.call(peer, "read", { kind = "song" }).result.items[1]
  eq(row.groove.on, false)
  eq(#row.groove.amounts, 4)
  eq(row.metronome.on, false)
  eq(row.metronome.beatsPerBar, 0)
  eq(row.metronome.precount, false)
  ok(math.abs(row.metronome.volumeDb + 3) < 1e-3, "the metronome's volume in dB")
  eq(row.editing.editStep, 2)
  eq(row.editing.quantize, false)
  eq(row.editing.recordTo, "pattern")
  ok(math.abs(row.headroomDb + 6) < 1e-3)
  eq(row.artist, "Somebody")
  eq(row.commentsCut, true)
  ok(#row.comments <= 1000 and row.comments:sub(-1):byte() ~= 0xC3, "cut on a character's start")
  H.no_dialogs()
end)

