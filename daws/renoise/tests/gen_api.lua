-- Builds renoise_api.lua, every class and member name in Renoise's Lua API definitions, so the
-- mock refuses names Renoise doesn't have.
-- Usage: luajit gen_api.lua <definitions library dir> <out file>
-- The definitions: Renoise.app/Contents/Resources/Scripts/Types/renoise/library, or the
-- library folder of github.com/renoise/definitions.

local root, out_path = arg[1], arg[2]
assert(root and out_path, "usage: luajit gen_api.lua <library dir> <out file>")

local classes = {}

local function class(name)
  local c = classes[name]
  if not c then
    c = { bases = {}, members = {} }
    classes[name] = c
  end
  return c
end

local function parse(path)
  local current, enum_table
  for line in io.lines(path) do
    local name, bases = line:match("^%-%-%-@class%s+([%w_.]+)%s*:?%s*(.*)$")
    if name then
      current = class(name)
      for base in bases:gmatch("[%w_.]+") do
        if base ~= "table" then current.bases[base] = true end
      end
    end
    local field = line:match("^%-%-%-@field%s+([%w_]+)")
    if field and current then current.members[field] = true end
    local owner, method = line:match("^function%s+([%w_.]+)[.:]([%w_]+)%s*%(")
    if owner then class(owner).members[method] = true end
    local target, constant = line:match("^(renoise[%w_.]*)%.([%w_]+)%s*=")
    if target and not line:match("^renoise[%w_.]*%s*=%s*{") then class(target).members[constant] = true end
    local enum_target = line:match("^(renoise[%w_.]*)%s*=%s*{%s*$")
    if enum_target then
      enum_table = class(enum_target)
    elseif enum_table then
      if line:match("^}") then
        enum_table = nil
      else
        local key = line:match("^%s+([%w_]+)%s*=")
        if key then enum_table.members[key] = true end
      end
    end
  end
end

local listing = io.popen('find "' .. root .. '" -name "*.lua" | sort')
for path in listing:lines() do parse(path) end
listing:close()

local names = {}
for name in pairs(classes) do names[#names + 1] = name end
table.sort(names)

local out = { "-- Generated by gen_api.lua from Renoise's Lua API definitions (API 6.2; MIT, github.com/renoise/definitions). Don't edit.", "return {" }
for _, name in ipairs(names) do
  local c = classes[name]
  local bases, members = {}, {}
  for b in pairs(c.bases) do bases[#bases + 1] = string.format("%q", b) end
  for m in pairs(c.members) do members[#members + 1] = string.format("%q", m) end
  table.sort(bases)
  table.sort(members)
  out[#out + 1] = string.format("  [%q] = { bases = { %s }, members = { %s } },", name, table.concat(bases, ", "), table.concat(members, ", "))
end
out[#out + 1] = "}"
local f = assert(io.open(out_path, "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print(string.format("%d classes", #names))
